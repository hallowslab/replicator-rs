use std::env;
use std::fs;
use std::path::PathBuf;

const DEFAULT_S3_MULTIPART_THRESHOLD: u64 = 8 * 1024 * 1024;
const DEFAULT_S3_MAX_PART_SIZE: u64 = 50 * 1024 * 1024;

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let build_toml = manifest_dir.join("build.toml");

    println!("cargo:rerun-if-changed=build.toml");

    let parsed = if build_toml.exists() {
        let raw = fs::read_to_string(&build_toml).unwrap();
        raw.parse::<toml::Value>().unwrap()
    } else {
        toml::Value::Table(Default::default())
    };

    let s3 = parsed.get("s3").and_then(|s| s.as_table());
    let u64_val = |k: &str| -> Option<u64> {
        s3.and_then(|t| t.get(k))
            .and_then(|v| v.as_integer())
            .map(|v| v as u64)
    };
    let multipart_threshold_bytes =
        u64_val("multipart_threshold_bytes").unwrap_or(DEFAULT_S3_MULTIPART_THRESHOLD);
    let max_part_size_bytes =
        u64_val("max_part_size_bytes").unwrap_or(DEFAULT_S3_MAX_PART_SIZE);

    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let code = format!(
        "// generated by build.rs from build.toml - do not edit\n\
         pub const S3_DEFAULT_MULTIPART_THRESHOLD_BYTES: u64 = {multipart_threshold_bytes};\n\
         pub const S3_DEFAULT_MAX_PART_SIZE_BYTES: u64 = {max_part_size_bytes};\n",
        multipart_threshold_bytes = multipart_threshold_bytes,
        max_part_size_bytes = max_part_size_bytes,
    );
    fs::write(out_dir.join("replicator_defaults.rs"), code).unwrap();
}